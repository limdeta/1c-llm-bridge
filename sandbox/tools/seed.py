# -*- coding: utf-8 -*-
"""Наполнение базы «Волшебный магазин»: товары, контрагенты, закупки, продажи."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "bridge"))
from onec import OneC


def run(c, label, code):
    try:
        r = c.execute(code)
        print(f"  {label}: {r}")
        return r
    except Exception as e:
        print(f"  {label} FAIL: {str(e)[:300]}")
        raise


with OneC() as c:
    # --- Очистка (идемпотентность) ---
    print("== Очистка предыдущих данных ==")
    run(c, "документы", (
        "Выборка = Документы.ПродажаТовара.Выбрать();"
        "Пока Выборка.Следующий() Цикл Выборка.Ссылка.ПолучитьОбъект().Удалить(); КонецЦикла;"
        "Выборка = Документы.ЗакупкаТовара.Выбрать();"
        "Пока Выборка.Следующий() Цикл Выборка.Ссылка.ПолучитьОбъект().Удалить(); КонецЦикла;"
        "Результат = \"OK\";"
    ))
    run(c, "справочники", (
        "Выборка = Справочники.Товары.Выбрать();"
        "Пока Выборка.Следующий() Цикл Выборка.Ссылка.ПолучитьОбъект().Удалить(); КонецЦикла;"
        "Выборка = Справочники.Контрагенты.Выбрать();"
        "Пока Выборка.Следующий() Цикл Выборка.Ссылка.ПолучитьОбъект().Удалить(); КонецЦикла;"
        "Результат = \"OK\";"
    ))

    print("\n== Товары ==")
    goods = [
        ("Волшебная палочка Олливандера", "Палочки", 7.0, 3.0, 95, "Классическая палочка из английского дуба с сердцевиной из пера феникса."),
        ("Палочка из бузины (Бузинная)", "Палочки", 15.0, 8.0, 100, "Легендарная палочка, когда-то принадлежавшая Геллерту Грин-де-Вальду."),
        ("Палочка из остролиста", "Палочки", 6.5, 2.5, 80, "Палочка Гарри Поттера: остролист и перо феникса."),
        ("Амортенция (приворотное зелье)", "Зелья", 12.0, 5.0, 60, "Самое сильное любовное зелье, переливается перламутром."),
        ("Феликс Фелицис (Жидкая удача)", "Зелья", 20.0, 9.0, 90, "Дарит невероятную удачу на целый день. Запрещено на турнирах."),
        ("Сыворотка правды", "Зелья", 8.0, 3.5, 40, "Заставляет говорить правду. Применять осторожно."),
        ("Хрустальный шар предсказаний", "ХрустальныеШары", 25.0, 12.0, 70, "Настоящий хрустальный шар из зала предсказаний Хогвартса."),
        ("Хрустальный шар малый (сувенир)", "ХрустальныеШары", 5.0, 2.0, 30, "Сувенирный шар для начинающих провидцев."),
        ("Чудовищная книга о чудовищах", "Книги", 9.0, 4.0, 50, "Учебник по уходу за магическими существами. Кусается."),
        ("Метла «Нимбус-2001»", "Прочее", 40.0, 25.0, 85, "Гоночная метла нового поколения."),
    ]
    refs = {}
    for name, vid, price, cost, power, desc in goods:
        code = (
            "Т = Справочники.Товары.СоздатьЭлемент();"
            f"Т.Наименование = \"{name}\";"
            f"Т.ВидТовара = Перечисления.ВидыТоваров.{vid};"
            f"Т.ЦенаПродажи = {price};"
            f"Т.ЦенаЗакупки = {cost};"
            f"Т.МагическаяСила = {power};"
            f"Т.Описание = \"{desc}\";"
            "Т.Записать();"
            "Результат = XMLСтрока(Т.Ссылка);"
        )
        refs[name] = run(c, name, code)

    print("\n== Контрагенты ==")
    kontragents = [
        ("Олливандер", "Поставщик", "Лондон, Косой переулок, 8", "Сова-экспресс"),
        ("Волшебные зелья Лтд", "Поставщик", "Хогсмид, аллея зелий", "Совёнок"),
        ("Хогвартс (закупки)", "Покупатель", "Хогвартс, Шотландия", "Школа"),
        ("Косой переулок (розница)", "Покупатель", "Косой переулок", "Лавка"),
        ("Гарри Поттер", "Покупатель", "Тисовая улица, 4, Литтл Уингинг", "Сова Хедвиг"),
    ]
    krefs = {}
    for name, vid, addr, phone in kontragents:
        code = (
            "К = Справочники.Контрагенты.СоздатьЭлемент();"
            f"К.Наименование = \"{name}\";"
            f"К.ВидКонтрагента = Перечисления.ВидыКонтрагентов.{vid};"
            f"К.Адрес = \"{addr}\";"
            f"К.Телефон = \"{phone}\";"
            "К.Записать();"
            "Результат = XMLСтрока(К.Ссылка);"
        )
        krefs[name] = run(c, name, code)

    print("\n== Закупки (приход на склад) ==")
    purchases = [
        ("Олливандер", [("Волшебная палочка Олливандера", 10), ("Палочка из бузины (Бузинная)", 3), ("Палочка из остролиста", 15)]),
        ("Волшебные зелья Лтд", [("Амортенция (приворотное зелье)", 8), ("Феликс Фелицис (Жидкая удача)", 5), ("Сыворотка правды", 12)]),
        ("Олливандер", [("Хрустальный шар предсказаний", 4), ("Хрустальный шар малый (сувенир)", 20)]),
        ("Волшебные зелья Лтд", [("Чудовищная книга о чудовищах", 15), ("Метла «Нимбус-2001»", 6)]),
    ]
    for supplier, items in purchases:
        lines = []
        for gname, qty in items:
            cost = [g[3] for g in goods if g[0] == gname][0]  # цена ЗАКУПКИ
            lines.append(f"Стр = Д.Товары.Добавить(); Стр.Товар = Справочники.Товары.НайтиПоНаименованию(\"{gname}\"); Стр.Количество = {qty}; Стр.Цена = {cost}; Стр.Сумма = {round(cost * qty, 2)};")
        code = (
            "Д = Документы.ЗакупкаТовара.СоздатьДокумент();"
            "Д.Дата = ТекущаяДата();"
            f"Д.Поставщик = Справочники.Контрагенты.НайтиПоНаименованию(\"{supplier}\");"
            + "".join(lines)
            + "Д.Записать(); Д.Записать(РежимЗаписиДокумента.Проведение);"
            "Результат = \"OK \" + Строка(Д.Номер);"
        )
        run(c, f"Закупка у {supplier} ({len(items)} поз.)", code)

    print("\n== Продажи ==")
    sales = [
        ("Гарри Поттер", [("Палочка из остролиста", 1), ("Сыворотка правды", 1)]),
        ("Хогвартс (закупки)", [("Феликс Фелицис (Жидкая удача)", 2), ("Хрустальный шар предсказаний", 1)]),
        ("Косой переулок (розница)", [("Амортенция (приворотное зелье)", 3), ("Чудовищная книга о чудовищах", 5)]),
        ("Гарри Поттер", [("Волшебная палочка Олливандера", 1), ("Хрустальный шар малый (сувенир)", 1)]),
    ]
    for buyer, items in sales:
        lines = []
        for gname, qty in items:
            price = [g[2] for g in goods if g[0] == gname][0]  # цена ПРОДАЖИ
            lines.append(f"Стр = Д.Товары.Добавить(); Стр.Товар = Справочники.Товары.НайтиПоНаименованию(\"{gname}\"); Стр.Количество = {qty}; Стр.Цена = {price}; Стр.Сумма = {round(price * qty, 2)};")
        code = (
            "Д = Документы.ПродажаТовара.СоздатьДокумент();"
            "Д.Дата = ТекущаяДата();"
            f"Д.Контрагент = Справочники.Контрагенты.НайтиПоНаименованию(\"{buyer}\");"
            + "".join(lines)
            + "Д.Записать(); Д.Записать(РежимЗаписиДокумента.Проведение);"
            "Результат = \"OK \" + Строка(Д.Номер);"
        )
        run(c, f"Продажа {buyer} ({len(items)} поз.)", code)

    print("\nНаполнение завершено.")
