# -*- coding: utf-8 -*-
"""Тест: обработка из расширения работает при включённой «Защите от опасных действий»."""
import os
import win32com.client

BASE_DIR = os.environ.get("ONEC_FILE", "")
EPF = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "build", "mcpExecutor.epf")


def conn_as(user, pwd=""):
    connector = win32com.client.Dispatch("V83.COMConnector")
    return connector.Connect(f'File={BASE_DIR};Usr="{user}";Pwd="{pwd}"')


# 1. Создаём пользователя с ЗАЩИТОЙ (по умолчанию ВКЛ)
admin = conn_as("Администратор")
users = admin.ПользователиИнформационнойБазы
u = users.СоздатьПользователя()
u.Имя = "СЗащитой"
u.ПолноеИмя = "Тест с защитой"
u.Пароль = ""
u.Роли.Добавить(admin.Метаданные.Роли.ПолныеПрава)
u.Записать()
print("1. Пользователь «СЗащитой» создан (защита по умолчанию ВКЛ)")

# Проверка флага
u2 = users.НайтиПоИмени("СЗащитой")
try:
    v = u2.ЗащитаОтОпасныхДействий
    print(f"   ЗащитаОтОпасныхДействий = {v}")
except Exception as e:
    print(f"   (флаг не читается: {e})")

# 2. Подключаемся как этот пользователь
c = conn_as("СЗащитой")
print("2. Подключение как «СЗащитой»: OK")

# 3. Внешний EPF должен быть ЗАБЛОКИРОВАН
try:
    ex = c.ВнешниеОбработки.Создать(EPF)
    print("3. Внешний EPF: ЗАГРУЗИЛСЯ?! (защита не сработала — странно)")
    ex.ВыполнитьКод("Результат = 1;")
except Exception as e:
    print(f"3. Внешний EPF заблокирован, как и ожидалось: {str(e)[:120]}")

# 4. Обработка ИЗ РАСШИРЕНИЯ должна работать БЕЗ снятия защиты
try:
    dp = c.Обработки.ИИМост_ИсполнительКода.Создать()
    print("4. Обработка из расширения: создана!")
    r = dp.ВыполнитьКод("Результат = 40 + 2;")
    print(f"   ВыполнитьКод(40+2) -> {r}")
    r = dp.ВыполнитьКод("Результат = Строка(ТекущаяДата());")
    print(f"   ТекущаяДата -> {r}")
    r = dp.ВыполнитьКод(
        'С = Новый Структура("имя", "Гарри"); Результат = С.имя + " Поттер";'
    )
    print(f"   Объекты -> {r}")
    print("5. ИТОГ: расширение работает у пользователя С ВКЛЮЧЁННОЙ защитой!")
except Exception as e:
    print(f"4. Обработка из расширения FAIL: {str(e)[:300]}")
