# -*- coding: utf-8 -*-
"""Финрезультат запросом + обороты по счетам циклом по движениям."""
import sys
sys.path.insert(0, "bridge")
from onec import OneC

Q2 = """
ВЫБРАТЬ
	СУММА(ВЫБОР КОГДА Д.СчетКт.Код = "90.01" ТОГДА Д.СуммаКт ИНАЧЕ 0 КОНЕЦ) КАК Выручка,
	СУММА(ВЫБОР КОГДА Д.СчетДт.Код = "90.02" ТОГДА Д.СуммаДт ИНАЧЕ 0 КОНЕЦ) КАК Себестоимость
ИЗ РегистрБухгалтерии.Хозрасчетный КАК Д
"""

OBOROTY = """ТЗ = Новый ТаблицаЗначений;
ТЗ.Колонки.Добавить("Счет");
ТЗ.Колонки.Добавить("Дт");
ТЗ.Колонки.Добавить("Кт");
Запрос = Новый Запрос("ВЫБРАТЬ Д.СчетДт КАК Счет, Д.СуммаДт КАК Сумма, Д.СуммаКт КАК СуммаКт, Д.СчетКт КАК СчетКт ИЗ РегистрБухгалтерии.Хозрасчетный КАК Д");
Выборка = Запрос.Выполнить().Выбрать();
Пока Выборка.Следующий() Цикл
	Стр = ТЗ.Найти(Выборка.Счет.Код, "Счет");
	Если Стр = Неопределено Тогда
		Стр = ТЗ.Добавить();
		Стр.Счет = Выборка.Счет.Код;
		Стр.Дт = 0;
		Стр.Кт = 0;
	КонецЕсли;
	Стр.Дт = Стр.Дт + Выборка.Сумма;
	Стр2 = ТЗ.Найти(Выборка.СчетКт.Код, "Счет");
	Если Стр2 = Неопределено Тогда
		Стр2 = ТЗ.Добавить();
		Стр2.Счет = Выборка.СчетКт.Код;
		Стр2.Дт = 0;
		Стр2.Кт = 0;
	КонецЕсли;
	Стр2.Кт = Стр2.Кт + Выборка.СуммаКт;
КонецЦикла;
Список = "";
ТЗ.Сортировать("Счет");
Для Каждого Стр Из ТЗ Цикл
	Список = Список + Стр.Счет + ": Дт=" + Формат(Стр.Дт, "ЧДЦ=2") + " Кт=" + Формат(Стр.Кт, "ЧДЦ=2") + " | ";
КонецЦикла;
Результат = Список;"""

with OneC() as c:
    print("=== Финансовый результат ===")
    r = c.query(Q2)
    rev, cost = r["rows"][0]
    print(f"  Выручка (90.01) = {rev}")
    print(f"  Себестоимость (90.02) = {cost}")
    print(f"  Прибыль = {round(rev - cost, 2)}")

    print("\n=== Обороты по счетам ===")
    print(" ", c.execute(OBOROTY))
