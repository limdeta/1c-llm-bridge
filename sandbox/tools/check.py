# -*- coding: utf-8 -*-
"""Проверка остатков и финансовых итогов."""
import sys, os, json
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "bridge"))
from onec import OneC

with OneC() as c:
    print("== Остатки на складе ==")
    r = c.query("""
        ВЫБРАТЬ
            Товары.Наименование КАК Товар,
            ЕСТЬNULL(Остатки.КоличествоОстаток, 0) КАК Остаток
        ИЗ
            Справочник.Товары КАК Товары
            ЛЕВОЕ СОЕДИНЕНИЕ РегистрНакопления.ОстаткиТоваров.Остатки(&Дата, ) КАК Остатки
            ПО Товары.Ссылка = Остатки.Товар
        УПОРЯДОЧИТЬ ПО Товар
    """, {"Дата": "2099-12-31T00:00:00"}, limit=50)
    for row in r["rows"]:
        print(f"  {row[0]}: {row[1]}")

    print("\n== Выручка по товарам ==")
    r = c.query("""
        ВЫБРАТЬ
            Товары.Наименование КАК Товар,
            СУММА(Продажи.КоличествоОборот) КАК Кол,
            СУММА(Продажи.СуммаОборот) КАК Выручка,
            СУММА(Продажи.СебестоимостьОборот) КАК Себестоимость
        ИЗ
            РегистрНакопления.Продажи.Обороты(&Начало, &Конец, ) КАК Продажи
            ЛЕВОЕ СОЕДИНЕНИЕ Справочник.Товары КАК Товары
            ПО Продажи.Товар = Товары.Ссылка
        СГРУППИРОВАТЬ ПО Товары.Наименование
        УПОРЯДОЧИТЬ ПО Выручка УБЫВ
    """, {"Начало": "2000-01-01T00:00:00", "Конец": "2099-12-31T00:00:00"}, limit=50)
    total_rev = total_cost = 0
    for row in r["rows"]:
        print(f"  {row[0]}: {row[1]} шт, выручка {row[2]}, себестоимость {row[3]}")
        total_rev += row[2]; total_cost += row[3]

    print("\n== Итоги (маленькая бухгалтерия) ==")
    print(f"  Выручка (продажи):      {total_rev}")
    print(f"  Себестоимость продаж:   {total_cost}")
    print(f"  Прибыль:                {round(total_rev - total_cost, 2)}")
    r = c.query("""
        ВЫБРАТЬ
            СУММА(Закупки.СуммаОборот) КАК Затраты,
            СУММА(Закупки.КоличествоОборот) КАК Кол
        ИЗ РегистрНакопления.Закупки.Обороты(&Начало, &Конец, ) КАК Закупки
    """, {"Начало": "2000-01-01T00:00:00", "Конец": "2099-12-31T00:00:00"})
    print(f"  Затраты на закупки:     {r['rows'][0][0]} ({r['rows'][0][1]} ед.)")
